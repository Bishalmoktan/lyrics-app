import { GoogleGenAI } from "@google/genai";

interface SpamCheckResult {
  isSpam: boolean;
  reason: string;
}

export async function spaming(
  name: string,
  message: string
): Promise<SpamCheckResult> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error("GEMINI_API_KEY is required");
  }

  // Initialize the SDK
  const ai = new GoogleGenAI({ apiKey });

const prompt = `
You are an intelligent spam detection system.

Analyze BOTH the user name and the message content to determine whether the submission is spam.

Spam indicators may include (but are not limited to):
- Promotional or marketing intent
- Suspicious links or contact details
- Repetitive, meaningless, or autogenerated text
- Scam, phishing, or fraud-related content
- Inappropriate or abusive language
- Fake, random, or promotional-looking user names (e.g. keywords, URLs, excessive numbers)

Respond ONLY with valid JSON in the following format:
{
  "isSpam": boolean,
  "reason": "Short explanation referencing the name and/or message"
}

User Name: "${name}"
Message: "${message}"
`.trim();


  try {
    // Call the API with Gemini 2.5 Flash
    const response = await ai.models.generateContent({
      model: "gemma-3-27b-it",
      contents: prompt,
    });

    const text = response.text ?? "";

    // Extract only JSON from the response
    const jsonMatch = text.match(/\{[\s\S]*\}/);
    if (!jsonMatch) {
      return {
        isSpam: true,
        reason: "AI returned unexpected output",
      };
    }

    const parsed = JSON.parse(jsonMatch[0]) as SpamCheckResult;
    return parsed;
  } catch (err) {
    console.error("Gemini API error:", err);
    return {
      isSpam: false,
      reason: "AI service error",
    };
  }
}
